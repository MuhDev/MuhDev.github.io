const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const site = `https://${read("CNAME").trim()}`;
const { portfolioData, projectPresentation } = vm.runInNewContext(
  `${read("assets/js/data.js")}\n({ portfolioData, projectPresentation })`
);
const control = { addEventListener() {}, setAttribute() {} };
const { translations, projectUrl } = vm.runInNewContext(`${read("assets/js/i18n.js")}\n({ translations, projectUrl })`, {
  root: { lang: "ar", dataset: {} },
  document: { querySelector: () => control, querySelectorAll: () => [] }
});
const template = read("project.html");
const languages = { ar: "ar_SA", en: "en_US" };
const localize = (value, language) => typeof value === "string" ? value : value[language];
const escapeHtml = (value) => value.replace(/[&<>"']/g, (character) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
})[character]);

const publicUrl = (relativePath) => `${site}/${relativePath}`;
const sitemapUrls = [`${site}/`];

fs.mkdirSync(path.join(root, "work"), { recursive: true });

for (const { id } of portfolioData.projects) {
  const { name, summary } = projectPresentation[id];
  const imagePath = `assets/images/share/${id}.jpg`;
  fs.accessSync(path.join(root, imagePath));
  const image = publicUrl(imagePath);

  for (const [language, locale] of Object.entries(languages)) {
    const alternate = language === "ar" ? "en" : "ar";
    const relativePath = projectUrl(id, language);
    const canonical = publicUrl(relativePath);
    const projectName = escapeHtml(localize(name, language));
    const title = `${projectName} | ${escapeHtml(portfolioData.profile.name[language])}`;
    const description = escapeHtml(summary[language]);
    const imageAlt = language === "ar" ? `لقطات من واجهات ${projectName}` : `${projectName} interface screenshots`;

    const metadata = `  <link rel="canonical" href="${canonical}">
  <link rel="alternate" hreflang="${language}" href="${canonical}">
  <link rel="alternate" hreflang="${alternate}" href="${publicUrl(projectUrl(id, alternate))}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="MuhDev">
  <meta property="og:locale" content="${locale}">
  <meta property="og:locale:alternate" content="${languages[alternate]}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${description}">
  <meta property="og:image" content="${image}">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${imageAlt}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${title}">
  <meta name="twitter:description" content="${description}">
  <meta name="twitter:image" content="${image}">
  <meta name="twitter:image:alt" content="${imageAlt}">`;

    const html = template
      .replace('<html lang="ar" dir="rtl" data-theme="light">',
        `<html lang="${language}" dir="${language === "ar" ? "rtl" : "ltr"}" data-theme="light" data-case-id="${id}">`)
      .replace('  <meta charset="utf-8">', '  <meta charset="utf-8">\n  <base href="../">')
      .replace(/<title>[^<]+<\/title>/, `<title>${title}</title>`)
      .replace(/<meta name="description" content="[^"]+">/, `<meta name="description" content="${description}">`)
      .replace('  <meta name="robots" content="noindex">', metadata)
      .replaceAll('href="#main"', `href="${relativePath}#main"`)
      .replace(/(data-i18n="(\w+)"[^>]*>)[^<]*/g,
        (_, tag, key) => `${tag}${escapeHtml(translations[language][key])}`)
      .replace(/(aria-label=")[^"]+(" data-i18n-label="navigation")/,
        `$1${escapeHtml(translations[language].navigation)}$2`)
      .replace(/(data-i18n-label="(\w+)" aria-label=")[^"]+/,
        (_, tag, key) => `${tag}${escapeHtml(translations[language][key])}`)
      .replace('data-language-toggle lang="en" dir="ltr" aria-label="Switch to English">English',
        language === "en" ? 'data-language-toggle lang="ar" dir="rtl" aria-label="التبديل إلى العربية">العربية' : '$&')
      .replace(/      <h1 id="case-title"[^\n]+\n      <noscript>[^\n]+/, `      <header class="case-intro">
        <h1 id="case-title"><bdi>${projectName}</bdi></h1>
        <p class="case-summary">${description}</p>
      </header>`)
      .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by scripts/build-case-pages.cjs. -->");

    fs.writeFileSync(path.join(root, relativePath), html);
    sitemapUrls.push(canonical);
  }
}

fs.writeFileSync(path.join(root, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapUrls.map((url) => `  <url><loc>${escapeHtml(url)}</loc></url>`).join("\n")}
</urlset>
`);
